import { test, expect } from '@playwright/test';
test('資料から保存・再読込・部分点・復習まで', async ({ page }) => {
  await page.goto('/legacy');
  await expect(page.getByRole('heading', { name: '利益と現金は、なぜ違う？' })).toBeVisible();
  await page.getByRole('button', { name: '案件を始める' }).click();
  await expect(page.getByRole('textbox', { name: '保険料（3か月分）' })).toBeEnabled();
  await page.screenshot({ path: 'test-results/stage1-desktop.png', fullPage: true });
  await page.getByRole('textbox', { name: '保険料（3か月分）' }).fill('30,000');
  await page.getByRole('textbox', { name: '備品（1年分）' }).fill('240000');
  await page.getByLabel('どう考えた？（任意）').fill('保険は使った3か月分だけ費用にする。');
  await page.getByRole('button', { name: '下書きを保存', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('サーバーへの保存を確認');
  await page.reload();
  await expect(page.getByRole('textbox', { name: '保険料（3か月分）' })).toHaveValue('30,000');
  await page.getByRole('button', { name: '提出して振り返る' }).click();
  await expect(page.getByText('今回の部分点：5 / 10')).toBeVisible();
  await expect(page.getByRole('button', { name: '提出して振り返る' })).toBeDisabled();
  await page.reload();
  await expect(page.getByText('今回の部分点：5 / 10')).toBeVisible();
  await expect(page.getByText('次回：').first()).toBeVisible();
});
test('スマートフォンで横はみ出しなく開始・編集できる', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/legacy');
  await page.getByRole('button', { name: '案件を始める' }).click();
  await page.getByRole('textbox', { name: '保険料（3か月分）' }).fill('30000');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/stage1-mobile.png', fullPage: true });
});
test('競合の確認で未保存入力を消さず、選択後に保存できる', async ({ page, context }) => {
  await page.goto('/legacy');
  await page.getByRole('button', { name: '案件を始める' }).click();
  await expect(page).toHaveURL(/sessionId=/);
  const other = await context.newPage();
  await other.goto(page.url());
  await expect(other.getByRole('textbox', { name: '保険料（3か月分）' })).toBeEnabled();
  await other.getByRole('textbox', { name: '保険料（3か月分）' }).fill('100');
  await other.getByRole('button', { name: '下書きを保存', exact: true }).click();
  await expect(other.getByRole('status')).toContainText('サーバーへの保存を確認');
  await page.getByRole('textbox', { name: '保険料（3か月分）' }).fill('30000');
  await page.getByRole('button', { name: '下書きを保存', exact: true }).click();
  await page.getByRole('button', { name: '状態を確認・再試行' }).click();
  await expect(page.getByRole('textbox', { name: '保険料（3か月分）' })).toHaveValue('30000');
  await expect(page.getByRole('region', { name: '保存済み答案との比較' })).toContainText('100');
  await page.getByRole('button', { name: '手元の答案を保持する' }).click();
  await page.getByRole('button', { name: '下書きを保存', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('サーバーへの保存を確認');
  await page.reload();
  await expect(page.getByRole('textbox', { name: '保険料（3か月分）' })).toHaveValue('30000');
});
